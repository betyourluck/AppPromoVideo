export const messages = { ja, en, "zh-CN": zhCN } as const;

/**
 * キーに対応する翻訳文を取得する関数。
 * 変数プレースホルダー ({key}) の置換に対応。
 *
 * rev30: 置換は**1 回の走査**で行う。値を置換パターンとして解釈させない (`$&` がパスやエラー文言に入りうる) /
 * 差し込んだ値の中の `{…}` を後の置換で拾わない / params に無い名前はそのまま残す。
 */
export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const dict: Record<string, string> = messages[currentLang.value] ?? messages.ja;
  const text = dict[key] ?? messages.ja[key] ?? key;
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole));
}
