/**
 * 軽量・型安全な UI 多言語化 (i18n) モジュール。
 * 日本語 (ja)、英語 (en)、簡体字中国語 (zh-CN) をサポート。
 * localStorage "apppromo.ui_lang" に永続化。
 *
 * rev30:
 * - **ja が正本**。en / zh-CN は `Record<MessageKey, string>` で型を縛る — キーの欠けも余りも型検査で落ちる
 *   (件数の比較だけでは「1 つ欠けて 1 つ余る」を見逃す)。
 * - 強調と等幅は文言の中に `<b>…</b>` / `<mono>…</mono>` と書き、`components/Rich.vue` で出す (解析は `rich.ts`)。
 * - 日本語の文言は、多言語化する前に画面に出ていたものと同じ (言い換えていない)。
 * - 画面に出る文言をコードに直書きしない (網は noHardcodedJapanese.test.ts)。
 */
import { ref } from "vue";

export type UiLang = "ja" | "en" | "zh-CN";

export interface LangOption {
  code: UiLang;
  label: string;
}

export const UI_LANGUAGES: LangOption[] = [
  { code: "ja", label: "日本語" },
  { code: "en", label: "English" },
  { code: "zh-CN", label: "简体中文" },
];

const STORAGE_KEY = "apppromo.ui_lang";

function loadSavedLang(): UiLang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "zh-CN" || saved === "ja") return saved;
  } catch {
    /* storage unavailable */
  }
  return "ja";
}

export const currentLang = ref<UiLang>(loadSavedLang());

export function setLang(lang: UiLang): void {
  currentLang.value = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* storage unavailable */
  }
}

